// Helper: Get N randomized questions with randomized option choices
export const getQuestionsForGame = (gameKey, count = 5) => {
  const bank = QUESTION_BANKS[gameKey] || QUESTION_BANKS.biscuit;
  // Shuffle questions array
  const shuffled = [...bank].sort(() => 0.5 - Math.random());
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  // Shuffle options within each question so the correct answer is never always in the same position
  return selected.map(q => {
    if (!q.options || !Array.isArray(q.options)) {
      return { ...q };
    }
    const shuffledOptions = [...q.options].sort(() => 0.5 - Math.random());
    return {
      ...q,
      options: shuffledOptions,
    };
  });
};
